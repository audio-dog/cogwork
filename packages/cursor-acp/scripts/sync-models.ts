import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { parseCursorModelList } from "../src/model.ts";

const agentBin = process.env.CURSOR_AGENT_BIN ?? "agent";
const target = fileURLToPath(new URL("../src/models.generated.ts", import.meta.url));
const check = process.argv.includes("--check");

const render = (ids: ReadonlyArray<string>) =>
  [
    `// Generated by \`pnpm --filter @cogwork/cursor-acp models:sync\` from \`${agentBin} --list-models\`. Do not edit.`,
    "",
    "export const cursorModels = [",
    ...ids.map((id) => `  ${JSON.stringify(id)},`),
    "] as const;",
    "",
    "export type CursorModel = (typeof cursorModels)[number];",
    "",
  ].join("\n");

const ids = parseCursorModelList(execFileSync(agentBin, ["--list-models"], { encoding: "utf8" }));

if (ids.length === 0) {
  throw new Error(`\`${agentBin} --list-models\` reported no models`);
}

const file = render(ids);

if (!check) {
  writeFileSync(target, file);
  console.log(`Wrote ${ids.length} Cursor model ids to ${target}`);
  process.exit(0);
}

if (readFileSync(target, "utf8") === file) {
  console.log(`Cursor model catalog is in sync (${ids.length} ids).`);
  process.exit(0);
}

console.error(`Cursor model catalog is stale. Run \`pnpm --filter @cogwork/cursor-acp models:sync\`.`);
process.exit(1);
