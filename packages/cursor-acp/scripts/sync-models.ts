import { spawn } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { createInterface } from "node:readline";
import { fileURLToPath } from "node:url";
import type { HarnessCatalogModel, HarnessModelOption } from "@cogwork/contracts";
import {
  type CursorAvailableModels,
  catalogModels,
  listAvailableModelsMethod,
  parameterizedModelPickerCapability,
} from "../src/catalog.ts";

const agentBin = process.env.CURSOR_AGENT_BIN ?? "agent";
const target = fileURLToPath(new URL("../src/models.generated.ts", import.meta.url));
const check = process.argv.includes("--check");

// Runs under `node --experimental-strip-types`, so there is no Effect runtime for the
// package's own probe to enter.
const initializeId = 1;
const listModelsId = 2;

const readPicker = () =>
  new Promise<CursorAvailableModels>((resolve, reject) => {
    const child = spawn(agentBin, ["acp"], { stdio: ["pipe", "pipe", "ignore"] });
    const send = (id: number, method: string, params: unknown) =>
      child.stdin.write(`${JSON.stringify({ jsonrpc: "2.0", id, method, params })}\n`);

    child.on("error", reject);
    createInterface({ input: child.stdout }).on("line", (line) => {
      const message = line.trim() ? JSON.parse(line) : { id: undefined };
      if (message.error) return reject(new Error(JSON.stringify(message.error)));
      if (message.id === initializeId) return send(listModelsId, listAvailableModelsMethod, {});
      if (message.id === listModelsId) {
        resolve(message.result as CursorAvailableModels);
        return child.kill();
      }
      // An inbound request, which the picker read has no handler for.
      if (message.id !== undefined && message.method !== undefined) {
        child.stdin.write(`${JSON.stringify({ jsonrpc: "2.0", id: message.id, result: {} })}\n`);
      }
    });

    send(initializeId, "initialize", {
      protocolVersion: 1,
      clientInfo: { name: "cogwork-models-sync", version: "0.0.0" },
      clientCapabilities: { _meta: parameterizedModelPickerCapability },
    });
  });

const renderChoices = (choices: ReadonlyArray<{ readonly value: string; readonly label: string }>) =>
  choices
    .map(
      (choice) =>
        `          { value: ${JSON.stringify(choice.value)}, label: ${JSON.stringify(choice.label)} },`,
    )
    .join("\n");

const renderOption = (option: HarnessModelOption) =>
  [
    "      {",
    `        id: ${JSON.stringify(option.id)},`,
    `        label: ${JSON.stringify(option.label)},`,
    `        fallback: ${JSON.stringify(option.fallback)},`,
    "        choices: [",
    renderChoices(option.choices),
    "        ],",
    "      },",
  ].join("\n");

const renderOptions = (options: HarnessCatalogModel["options"]) =>
  options && options.length > 0
    ? ["    options: [", options.map(renderOption).join("\n"), "    ],"]
    : ["    options: [],"];

const renderModel = (model: HarnessCatalogModel) =>
  [
    "  {",
    `    value: ${JSON.stringify(model.value)},`,
    `    label: ${JSON.stringify(model.label)},`,
    ...renderOptions(model.options),
    "  },",
  ].join("\n");

const render = (models: ReadonlyArray<HarnessCatalogModel>) =>
  [
    `// Generated by \`pnpm --filter @cogwork/cursor-acp models:sync\` from \`${agentBin} acp\``,
    `// \`${listAvailableModelsMethod}\`. Do not edit.`,
    'import type { HarnessCatalogModel } from "@cogwork/contracts";',
    "",
    "const models = [",
    models.map(renderModel).join("\n"),
    "] as const satisfies ReadonlyArray<HarnessCatalogModel>;",
    "",
    "export const cursorModelCatalog = { models };",
    "",
    "export const cursorModels = models.map((model) => model.value);",
    "",
    'export type CursorModel = (typeof models)[number]["value"];',
    "",
  ].join("\n");

const models = catalogModels(await readPicker());

if (models.length === 0) {
  throw new Error(`\`${agentBin} acp\` answered ${listAvailableModelsMethod} with no models`);
}

const file = render(models);

if (!check) {
  writeFileSync(target, file);
  console.log(`Wrote ${models.length} Cursor base models to ${target}`);
  process.exit(0);
}

if (readFileSync(target, "utf8") === file) {
  console.log(`Cursor model catalog is in sync (${models.length} base models).`);
  process.exit(0);
}

console.error(`Cursor model catalog is stale. Run \`pnpm --filter @cogwork/cursor-acp models:sync\`.`);
process.exit(1);
