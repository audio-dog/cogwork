import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { HarnessModelOptionDescriptor } from "@cogwork/contracts";
import { createCursorModelCatalog } from "../src/model.ts";

const agentBin = process.env.CURSOR_AGENT_BIN ?? "agent";
const target = fileURLToPath(new URL("../src/models.generated.ts", import.meta.url));
const oxfmtBin = fileURLToPath(new URL("../../../node_modules/.bin/oxfmt", import.meta.url));
const check = process.argv.includes("--check");
const processLimits = { encoding: "utf8", timeout: 10_000, maxBuffer: 1_048_576 } as const;

const render = (catalog: ReturnType<typeof createCursorModelCatalog>["catalog"]) => {
  const descriptors = catalog.models.flatMap(({ options }) => options ?? []);
  const uniqueDescriptors = Array.from(
    new Map(descriptors.map((descriptor) => [JSON.stringify(descriptor), descriptor])).values(),
  );
  const descriptorName = (descriptor: (typeof descriptors)[number]) =>
    [
      `${descriptor.id}Option`,
      descriptor.defaultValue,
      ...HarnessModelOptionDescriptor.match(descriptor, {
        boolean: () => [],
        select: ({ values }) => values.map(({ value }) => value),
      }),
    ]
      .join("_")
      .replaceAll("-", "_");
  const models = catalog.models.map((model) => {
    const options = model.options?.map(descriptorName).join(",");
    return `model(${JSON.stringify(model.value)},${JSON.stringify(model.label)},${model.default}${options ? `,[${options}]` : ""})`;
  });
  const source = [
    `// Generated by \`pnpm --filter @cogwork/cursor-acp models:sync\` from \`${agentBin} --list-models\`. Do not edit.`,
    "",
    'import type { HarnessManagedCatalog, HarnessManagedCatalogModel, HarnessModelOptionDescriptor } from "@cogwork/contracts";',
    "",
    'type SelectOption = Extract<HarnessModelOptionDescriptor, { type: "select" }>;',
    'const selectOption = (id: string, label: string, values: ReadonlyArray<readonly [string, string]>, defaultValue: string) => ({type:"select" as const,id,label,values:values.map(([value,valueLabel])=>({value,label:valueLabel})),defaultValue}) satisfies SelectOption;',
    'const model = (value: string, label: string, defaultModel: boolean, options?: HarnessManagedCatalogModel["options"]) => ({value,label,default:defaultModel,...(options ? { options } : {})}) satisfies HarnessManagedCatalogModel;',
    "",
    ...uniqueDescriptors.map((descriptor) =>
      HarnessModelOptionDescriptor.match(descriptor, {
        boolean: (option) => `const ${descriptorName(option)} = ${JSON.stringify(option)} as const;`,
        select: (option) => {
          const values = option.values.map(({ value, label }) => [value, label]);
          return `const ${descriptorName(option)} = selectOption(${JSON.stringify(option.id)},${JSON.stringify(option.label)},${JSON.stringify(values)},${JSON.stringify(option.defaultValue)});`;
        },
      }),
    ),
    "",
    `export const cursorModels = ${JSON.stringify(catalog.rawModelIds)} as const;`,
    "",
    "export const cursorCatalog = {",
    `generatedAgainst:${JSON.stringify(catalog.generatedAgainst)},`,
    `models:[${models.join(",")}],`,
    "rawModelIds:cursorModels,",
    `rawModelSelections:${JSON.stringify(catalog.rawModelSelections)},`,
    "} satisfies HarnessManagedCatalog;",
    "",
    "export type CursorModel = (typeof cursorModels)[number];",
    "",
  ].join("\n");
  return execFileSync(oxfmtBin, ["--disable-nested-config", `--stdin-filepath=${target}`], {
    input: source,
    ...processLimits,
  });
};

const version = execFileSync(agentBin, ["--version"], processLimits).trim();
const output = execFileSync(agentBin, ["--list-models"], processLimits);
const { catalog, opaqueModelIds } = createCursorModelCatalog(output, version);

if (catalog.rawModelIds.length === 0) {
  throw new Error(`\`${agentBin} --list-models\` reported no models`);
}

const file = render(catalog);
const opaqueSummary = opaqueModelIds.length > 0 ? ` Opaque: ${opaqueModelIds.join(", ")}.` : "";

if (!check) {
  writeFileSync(target, file);
  console.log(
    `Wrote ${catalog.models.length} Cursor models from ${catalog.rawModelIds.length} native ids to ${target}.${opaqueSummary}`,
  );
  process.exit(0);
}

if (readFileSync(target, "utf8") === file) {
  console.log(
    `Cursor model catalog is in sync (${catalog.models.length} models, ${catalog.rawModelIds.length} native ids).${opaqueSummary}`,
  );
  process.exit(0);
}

console.error(`Cursor model catalog is stale. Run \`pnpm --filter @cogwork/cursor-acp models:sync\`.`);
process.exit(1);
