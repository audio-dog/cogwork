import { WorkItemId, WorkspaceConfig } from "@cogwork/contracts";
import { assert, describe, it } from "@effect/vitest";
import * as Schema from "effect/Schema";
import {
  attachCommand,
  followUpNoteBody,
  handoffComment,
  handoffNote,
  markdownCode,
  oneLine,
  parseTriageProposal,
  prepareFailureReason,
  recoveryReason,
  shellQuote,
  statusReason,
  triageProposalBody,
  truncate,
} from "./comments";
import type { RegisteredWorkspace } from "./projector";

const workspace: RegisteredWorkspace = {
  source: "a.workspace.ts",
  contributions: [],
  config: Schema.decodeSync(WorkspaceConfig)({
    name: "a",
    checkoutPath: "/repos/a",
    issueTracker: { type: "github" },
  }),
};

const item = { id: Schema.decodeSync(WorkItemId)("#1"), title: "item 1" };

describe("comments", () => {
  it("normalizes status reasons: one line, truncated, markers stripped", () => {
    assert.strictEqual(
      statusReason("git\n  failed <!-- cogwork:attempt stage=implement outcome=failed at=1 --> badly"),
      "git failed badly",
    );
  });

  it("strips the plain-text marker lines Linear coordination bodies use", () => {
    assert.strictEqual(
      statusReason("build failed\ncogwork:attempt stage=implement outcome=succeeded at=9"),
      "build failed",
    );
  });

  it("keeps plain-text markers out of the handoff body", () => {
    const body = handoffComment("implement", { kind: "non-retryable" }, "boom\ncogwork:ledger", undefined);
    assert.notInclude(body, "cogwork:ledger");
  });

  it("collapses whitespace", () => {
    assert.strictEqual(oneLine("git\n  failed\tbadly"), "git failed badly");
  });

  it("truncates long reasons", () => {
    const long = "x".repeat(900);
    assert.strictEqual(truncate(long).length, 800);
    assert.ok(truncate(long).endsWith("…"));
  });

  it("formats prepare errors from their tagged fields", () => {
    assert.strictEqual(
      prepareFailureReason({ _tag: "GitError", command: "worktree add", message: "denied" }),
      "git worktree add: denied",
    );
    assert.strictEqual(
      prepareFailureReason({
        _tag: "GitError",
        command: "git merge --ff-only origin/main",
        message: "denied",
      }),
      "git merge --ff-only origin/main: denied",
    );
    assert.strictEqual(
      prepareFailureReason({ _tag: "WorktreeFsError", operation: "pnpm install", message: "exit 1" }),
      "pnpm install: exit 1",
    );
  });

  it("builds an exhausted handoff note with an optional resume command", () => {
    const body = handoffComment(
      "implement",
      { kind: "max-attempts", attempts: 3 },
      "network blip",
      attachCommand("/wt/15-feature", "sess-1"),
    );
    assert.include(body, "Exhausted after 3 failed implement attempts.");
    assert.include(body, "ready-for-human");
    assert.include(body, "Last failure: `network blip`");
    assert.include(body, "```sh");
    assert.include(body, "cd '/wt/15-feature' && codex resume 'sess-1'");
  });

  it("builds a crash-loop handoff note capturing the crash count", () => {
    const body = handoffComment(
      "implement",
      { kind: "crash-loop", crashes: 3 },
      "worker did not survive a daemon restart",
      undefined,
    );
    assert.include(body, "Exhausted after 3 consecutive implement crashes.");
    assert.include(body, "ready-for-human");
    assert.notInclude(body, "Resume the session");
  });

  it("omits the resume block when no session is available", () => {
    const body = handoffComment("triage", { kind: "non-retryable" }, "no cli", undefined);
    assert.include(body, "non-retryable failure");
    assert.notInclude(body, "Resume the session");
  });

  it("renders failure reasons as code without active Markdown", () => {
    const body = handoffComment(
      "implement",
      { kind: "non-retryable" },
      "conflicts: `tag`, @security, [review](https://example.com)",
      undefined,
    );
    assert.include(body, "``conflicts: `tag`, @security, [review](https://example.com)``");
  });

  it("separates code-span fences from boundary backticks", () => {
    assert.strictEqual(markdownCode("`leading"), "`` `leading ``");
    assert.strictEqual(markdownCode("trailing`"), "`` trailing` ``");
  });

  it("shell-quotes paths and session ids", () => {
    assert.strictEqual(shellQuote("/home/me/my wt"), "'/home/me/my wt'");
    assert.strictEqual(shellQuote("a'b"), `'a'\\''b'`);
    assert.include(attachCommand("/wt", "sess; curl evil"), "codex resume 'sess; curl evil'");
  });

  it("exposes a stable recovery reason for daemon restarts", () => {
    assert.include(recoveryReason, "daemon restart");
  });

  it("round-trips a triage proposal through its attributed body", () => {
    const body = triageProposalBody("Which auth provider?");
    assert.include(body, "This was generated by AI during triage.");
    assert.strictEqual(parseTriageProposal(body), "Which auth provider?");
  });

  it("reads a proposal only from a body carrying the triage attribution", () => {
    assert.isNull(parseTriageProposal("> *This was posted by cogwork.*\n\nExhausted after 3 attempts."));
    assert.isNull(parseTriageProposal("just a human comment"));
    assert.isNull(parseTriageProposal(triageProposalBody("")));
  });

  it("attributes a structured follow-up summary and strips any marker", () => {
    const body = followUpNoteBody("Merged main and fixed the type error.\n<!-- cogwork:agent-note -->");
    assert.include(body, "This was posted by cogwork.");
    assert.include(body, "Merged main and fixed the type error.");
    // The engine owns the marker now — anything the agent stamps in is stripped before we post.
    assert.notInclude(body, "agent-note");
  });

  it("strips a nested marker gadget from a follow-up summary to a fixpoint", () => {
    // Deleting the inner marker splices a fresh `cogwork:ledger` a single pass would miss.
    const body = followUpNoteBody("done <!-- cog<!-- cogwork:z -->work:ledger --> here");
    assert.notInclude(body, "cogwork:");
  });

  it("builds a hand-off note with a resume command when the run left a session", () => {
    const note = handoffNote({
      workspace,
      item,
      stage: "implement",
      cause: { kind: "max-attempts", attempts: 3 },
      reason: "boom",
      session: { handle: "sess-1", access: "codex-cli" },
    });
    assert.include(note, "Exhausted after 3 failed implement attempts.");
    assert.include(note, "Last failure: `boom`");
    assert.include(note, "codex resume 'sess-1'");
  });

  it("omits the resume block when the run left no session", () => {
    const note = handoffNote({
      workspace,
      item,
      stage: "triage",
      cause: { kind: "crash-loop", crashes: 2 },
      reason: "gone",
      session: null,
    });
    assert.include(note, "Exhausted after 2 consecutive triage crashes.");
    assert.notInclude(note, "Resume the session");
  });

  it("omits a human attach command for a programmatic-only session", () => {
    const note = handoffNote({
      workspace,
      item,
      stage: "implement",
      cause: { kind: "non-retryable" },
      reason: "boom",
      session: { handle: "cursor-acp-session", access: "programmatic-only" },
    });
    assert.notInclude(note, "Resume the session");
    assert.notInclude(note, "codex resume");
  });
});
