import type { ActionableItem, RunRecord, TokenUsage, TriageRole } from "@clanker-forge/contracts";
import { RunId, SessionId } from "@clanker-forge/contracts";
import * as Clock from "effect/Clock";
import * as Context from "effect/Context";
import * as Effect from "effect/Effect";
import * as Layer from "effect/Layer";
import * as Ref from "effect/Ref";
import * as Result from "effect/Result";
import * as Schema from "effect/Schema";
import * as Stream from "effect/Stream";
import { stripMarkers } from "./github/markers";
import { Harness, type HarnessEvent, type HarnessRequest } from "./Harness";
import { buildTriagePrompt, parseTriageDecision, type ResolvedStage, resolveTriage } from "./Playbook";
import type { RegisteredWorkspace } from "./projector";
import { RunLedger } from "./RunLedger";
import { WorkSource } from "./WorkSource";

interface RunAccumulator {
  readonly text: string;
  readonly session: string | null;
  readonly usage: TokenUsage | null;
}

const emptyAccumulator: RunAccumulator = { text: "", session: null, usage: null };

const decisionLine = /^\s*TRIAGE-DECISION:.*$/gim;

const proposalBody = (text: string) =>
  `> *This was generated by AI during triage.*\n\n${stripMarkers(text.replace(decisionLine, "")).trim()}`;

const mergeEvent = (acc: RunAccumulator, event: HarnessEvent): RunAccumulator => ({
  text: event.text ? acc.text + event.text : acc.text,
  session: event.sessionId ?? acc.session,
  usage: event.usage ?? acc.usage,
});

const claimant = (workspace: RegisteredWorkspace) => workspace.config.workSource.botLogin ?? "clanker-forge";

const withoutKey = (set: ReadonlySet<string>, key: string): ReadonlySet<string> => {
  const next = new Set(set);
  next.delete(key);
  return next;
};

const decodeRunId = Schema.decodeUnknownEffect(RunId);
const decodeSessionId = Schema.decodeUnknownEffect(SessionId);
const encodeJson = Schema.encodeEffect(Schema.UnknownFromJsonString);

const sessionOf = (raw: string | null) =>
  raw === null ? Effect.succeed(null) : decodeSessionId(raw).pipe(Effect.orElseSucceed(() => null));

export const make = Effect.gen(function* () {
  const workSource = yield* WorkSource;
  const harness = yield* Harness;
  const ledger = yield* RunLedger;
  const runCounter = yield* Ref.make(0);
  const inflight = yield* Ref.make<ReadonlySet<string>>(new Set());

  const nextRunId = (startedAtMillis: number) =>
    Ref.getAndUpdate(runCounter, (n) => n + 1).pipe(
      Effect.flatMap((n) => decodeRunId(`run-${startedAtMillis}-${n}`)),
      Effect.orDie,
    );

  const tryClaim = Effect.fn("Executor.tryClaim")(function* (
    workspace: RegisteredWorkspace,
    item: ActionableItem,
    at: number,
  ) {
    const claim = { by: claimant(workspace), claimedAtMillis: at };
    const result = yield* Effect.result(workSource.claim(workspace, item.id, claim));
    if (Result.isSuccess(result)) return true;
    yield* Effect.logWarning("triage claim failed", { item: item.id, error: result.failure });
    return false;
  });

  const persistEvent = Effect.fn("Executor.persistEvent")(function* (
    runId: RunId,
    seq: number,
    event: HarnessEvent,
  ) {
    const atMillis = yield* Clock.currentTimeMillis;
    const data = yield* encodeJson(event).pipe(Effect.orElseSucceed(() => "{}"));
    yield* ledger.appendEvent(runId, { seq, type: event.type, name: event.name, data, atMillis });
  });

  const foldRun = Effect.fn("Executor.foldRun")(function* (runId: RunId, request: HarnessRequest) {
    return yield* Stream.runFoldEffect(
      Stream.zipWithIndex(harness.run(request)),
      () => emptyAccumulator,
      (acc, [event, seq]) => Effect.map(persistEvent(runId, seq, event), () => mergeEvent(acc, event)),
    );
  });

  const applySuccess = Effect.fn("Executor.applySuccess")(function* (
    workspace: RegisteredWorkspace,
    item: ActionableItem,
    runId: RunId,
    acc: RunAccumulator,
  ) {
    const decision: TriageRole = parseTriageDecision(acc.text) ?? "ready-for-human";
    const session = yield* sessionOf(acc.session);
    const endedAtMillis = yield* Clock.currentTimeMillis;
    yield* workSource.comment(workspace, item.id, proposalBody(acc.text));
    yield* workSource.setRoles(workspace, item.id, { remove: ["needs-triage"], add: [decision] });
    yield* workSource.recordAttempt(workspace, item.id, {
      stage: "triage",
      outcome: "succeeded",
      atMillis: endedAtMillis,
    });
    yield* ledger.updateRun(runId, { status: "succeeded", session, usage: acc.usage, endedAtMillis });
  });

  const applyFailure = Effect.fn("Executor.applyFailure")(function* (
    workspace: RegisteredWorkspace,
    item: ActionableItem,
    runId: RunId,
    retryable: boolean,
  ) {
    const endedAtMillis = yield* Clock.currentTimeMillis;
    yield* workSource.recordAttempt(workspace, item.id, {
      stage: "triage",
      outcome: "failed",
      atMillis: endedAtMillis,
    });
    if (!retryable) {
      yield* workSource.setRoles(workspace, item.id, { remove: ["needs-triage"], add: ["ready-for-human"] });
    }
    yield* ledger.updateRun(runId, {
      status: retryable ? "failed" : "blocked",
      session: null,
      usage: null,
      endedAtMillis,
    });
  });

  const releaseClaim = Effect.fn("Executor.releaseClaim")(function* (
    workspace: RegisteredWorkspace,
    item: ActionableItem,
  ) {
    const result = yield* Effect.result(workSource.release(workspace, item.id));
    if (Result.isFailure(result)) {
      yield* Effect.logWarning("triage release failed", { item: item.id, error: result.failure });
    }
  });

  const runClaimed = Effect.fn("Executor.runClaimed")(function* (
    workspace: RegisteredWorkspace,
    item: ActionableItem,
    resolved: ResolvedStage,
    startedAtMillis: number,
  ) {
    const runId = yield* nextRunId(startedAtMillis);
    const record: RunRecord = {
      id: runId,
      workspace: workspace.config.name,
      workItem: item.id,
      stage: "triage",
      harness: resolved.harness,
      session: null,
      usage: null,
      status: "running",
      startedAtMillis,
      endedAtMillis: null,
    };
    yield* ledger.insertRun(record);
    const request: HarnessRequest = {
      harness: resolved.harness,
      checkoutPath: workspace.config.checkoutPath,
      prompt: buildTriagePrompt(resolved, { id: item.id, title: item.title }),
      model: resolved.model,
      sessionId: null,
    };
    const outcome = yield* Effect.result(foldRun(runId, request));
    yield* Result.isSuccess(outcome)
      ? applySuccess(workspace, item, runId, outcome.success)
      : applyFailure(workspace, item, runId, outcome.failure.retryable);
  });

  const execute = Effect.fn("Executor.execute")(function* (
    workspace: RegisteredWorkspace,
    item: ActionableItem,
  ) {
    const resolved = resolveTriage(workspace.config);
    if (item.stage !== "triage" || !resolved.enabled) {
      return;
    }
    const startedAtMillis = yield* Clock.currentTimeMillis;
    const claimed = yield* tryClaim(workspace, item, startedAtMillis);
    if (!claimed) {
      return;
    }
    yield* runClaimed(workspace, item, resolved, startedAtMillis).pipe(
      Effect.ensuring(releaseClaim(workspace, item)),
    );
  });

  const runIfIdle = Effect.fn("Executor.runIfIdle")(function* (
    workspace: RegisteredWorkspace,
    item: ActionableItem,
  ) {
    const key = `${workspace.config.name}:${item.id}`;
    const started = yield* Ref.modify(inflight, (set) =>
      set.has(key) ? [false, set] : [true, new Set(set).add(key)],
    );
    if (!started) {
      return;
    }
    yield* execute(workspace, item).pipe(
      Effect.catchCause((cause) => Effect.logWarning("triage run failed", { item: item.id, cause })),
      Effect.ensuring(Ref.update(inflight, (set) => withoutKey(set, key))),
      Effect.forkDetach,
    );
  });

  return { execute, runIfIdle } as const;
});

export class Executor extends Context.Service<Executor, Effect.Success<typeof make>>()(
  "@clanker-forge/engine/Executor",
) {}

export const layer = Layer.effect(Executor, make);
