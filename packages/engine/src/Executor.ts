import { branchName, checkoutPathFor, type WorktreeDivergedError, WorktreeManager } from "./Worktree";
import type { WorktreeFsError } from "./WorktreeFs";

type PrepareError = GitError | WorktreeFsError | WorktreeDivergedError;

interface RunAccumulator {
  readonly text: string;
  readonly session: string | null;
  readonly usage: TokenUsage | null;
}

interface StageOps {
  readonly resolved: ResolvedStage;
  readonly branch: string | null;
  readonly prepare: Effect.Effect<HarnessRequest, PrepareError>;
  readonly complete: (runId: RunId, acc: RunAccumulator) => Effect.Effect<void, WorkSourceError>;
  readonly handoffRole: TriageRole | null;
}

const harnessRequest = (
  resolved: ResolvedStage,
  checkoutPath: string,
  prompt: string,
  sessionId: string | null,
) => ({
  harness: resolved.harness,
  checkoutPath,
  prompt,
  model: resolved.model,
  effort: resolved.effort,
  sessionId,
});

const defaultFollowUp: FollowUpContext = {
  checks: "pending",
  humanCommentAtMillis: 0,
  noProgress: 0,
  stalled: false,
  fresh: false,
};

const decisionLine = /^\s*TRIAGE-DECISION:.*$/gim;

const proposalBody = (text: string) =>
  `> *This was generated by AI during triage.*\n\n${text.replace(decisionLine, "").trim()}`;

const warnTriageDecision = Effect.fn("Executor.warnTriageDecision")(function* (
  item: EligibleWork,
  decision: TriageDecision,
) {
  if (decision.source !== "sentinel") {
    return yield* Effect.logWarning("triage run emitted no decision sentinel", {
      item: item.id,
      source: decision.source,
      disposition: decision.disposition,
      applied: decision.role,
    });
  }
  if (decision.disposition && decision.disposition !== decision.sentinel) {
    yield* Effect.logWarning("triage sentinel disagrees with proposal disposition", {
      item: item.id,
      sentinel: decision.sentinel,
      disposition: decision.disposition,
      applied: decision.role,
    });
  }
});

const mergeEvent = (acc: RunAccumulator, event: HarnessEvent): RunAccumulator => ({
  text: event.text ? acc.text + event.text : acc.text,
  session: event.sessionId ?? acc.session,
  usage: event.usage ?? acc.usage,
});

const failedTerminal: HarnessEvent = {
  type: "RUN_FINISHED",
  name: null,
  text: null,
  sessionId: null,
  usage: null,
  finishReason: "failed",
};

const withFailureTerminal = (stream: Stream.Stream<HarnessEvent, HarnessError>) =>
  Stream.catchCause(stream, (cause) =>
    Stream.concat(Stream.succeed(failedTerminal), Stream.failCause(cause)),
  );

const retryableOf = (error: PrepareError | HarnessError) => {
  if (error._tag === "HarnessError") return error.retryable;
  return error._tag !== "WorktreeDivergedError";
};

const checkoutFor = (workspace: RegisteredWorkspace, item: EligibleWork) =>
  checkoutPathFor(workspace.config.checkoutPath, item, item.stage, workspace.config.worktrees);

const handoffCause = (retryable: boolean, attempts: number) =>
  retryable ? ({ kind: "max-attempts", attempts } as const) : ({ kind: "non-retryable" } as const);

const resumeFor = (workspace: RegisteredWorkspace, item: EligibleWork, session: SessionId | null) =>
  session ? attachCommand(checkoutFor(workspace, item), session) : undefined;

export const claimant = (workspace: RegisteredWorkspace) =>
  workspace.config.workSource.botLogin ?? "clanker-forge";

const decodeRunId = Schema.decodeUnknownEffect(RunId);
const decodeSessionId = Schema.decodeUnknownEffect(SessionId);
const encodeJson = Schema.encodeEffect(Schema.UnknownFromJsonString);

const sessionOf = (raw: string | null) =>
  raw === null ? Effect.succeed(null) : decodeSessionId(raw).pipe(Effect.orElseSucceed(() => null));

export const make = Effect.gen(function* () {
  const workSource = yield* WorkSource;
  const harness = yield* Harness;
  const ledger = yield* RunLedger;
  const bus = yield* RunEventBus;
  const worktrees = yield* WorktreeManager;
  const runCounter = yield* Ref.make(0);

  const nextRunId = (startedAtMillis: number) =>
    Ref.getAndUpdate(runCounter, (n) => n + 1).pipe(
      Effect.flatMap((n) => decodeRunId(`run-${startedAtMillis}-${n}`)),
      Effect.orDie,
    );

  const tryClaim = Effect.fn("Executor.tryClaim")(function* (
    workspace: RegisteredWorkspace,
    item: EligibleWork,
    at: number,
  ) {
    const claim = { by: claimant(workspace), claimedAtMillis: at, stage: item.stage };
    const result = yield* Effect.result(workSource.claim(workspace, item.id, claim));
    if (Result.isSuccess(result)) return true;
    yield* Effect.logWarning("claim failed", { stage: item.stage, item: item.id, error: result.failure });
    return false;
  });

  const persistEvent = Effect.fn("Executor.persistEvent")(function* (
    record: RunRecord,
    seq: number,
    event: HarnessEvent,
  ) {
    const atMillis = yield* Clock.currentTimeMillis;
    const data = yield* encodeJson(event).pipe(Effect.orElseSucceed(() => "{}"));
    yield* ledger.appendEvent(record.id, { seq, type: event.type, name: event.name, data, atMillis });
    yield* bus.publish(activityOf(record, seq, atMillis, event));
  });

  const foldRun = Effect.fn("Executor.foldRun")(function* (record: RunRecord, request: HarnessRequest) {
    const initial: RunAccumulator = { text: "", session: null, usage: null };
    return yield* Stream.runFoldEffect(
      Stream.zipWithIndex(withFailureTerminal(harness.run(request))),
      () => initial,
      (acc: RunAccumulator, [event, seq]: readonly [HarnessEvent, number]) =>
        Effect.map(persistEvent(record, seq, event), () => mergeEvent(acc, event)),
    );
  });

  const applyFailure = Effect.fn("Executor.applyFailure")(function* (
    workspace: RegisteredWorkspace,
    item: EligibleWork,
    handoffRole: TriageRole | null,
    runId: RunId,
    retryable: boolean,
    reason: string,
    session: SessionId | null,
  ) {
    const endedAtMillis = yield* Clock.currentTimeMillis;
    const attempts = item.priorFailures + 1;
    const exhausted = !retryable || attempts >= maxAttemptsPerStage;
    yield* Effect.logWarning("stage attempt failed", {
      stage: item.stage,
      item: item.id,
      reason,
      retryable,
      exhausted,
    });
    yield* workSource.recordAttempt(
      workspace,
      item.id,
      { stage: item.stage, outcome: "failed", atMillis: endedAtMillis },
      reason,
    );
    if (exhausted) {
      yield* workSource.setRoles(workspace, item.id, {
        remove: handoffRole ? [handoffRole] : [],
        add: ["ready-for-human"],
      });
      yield* workSource.note(
        workspace,
        item.id,
        handoffComment(
          item.stage,
          handoffCause(retryable, attempts),
          reason,
          resumeFor(workspace, item, session),
        ),
      );
    }
    yield* ledger.updateRun(runId, {
      status: exhausted ? "exhausted" : "failed",
      session: exhausted ? null : session,
      usage: null,
      endedAtMillis,
    });
  });

  const applyTriageSuccess = Effect.fn("Executor.applyTriageSuccess")(function* (
    workspace: RegisteredWorkspace,
    item: EligibleWork,
    runId: RunId,
    acc: RunAccumulator,
  ) {
    const decision = resolveTriageDecision(acc.text);
    yield* warnTriageDecision(item, decision);
    const session = yield* sessionOf(acc.session);
    const endedAtMillis = yield* Clock.currentTimeMillis;
    yield* workSource.note(workspace, item.id, proposalBody(acc.text));
    yield* workSource.setRoles(workspace, item.id, { remove: ["needs-triage"], add: [decision.role] });
    yield* workSource.recordAttempt(workspace, item.id, {
      stage: "triage",
      outcome: "succeeded",
      atMillis: endedAtMillis,
    });
    yield* ledger.updateRun(runId, { status: "succeeded", session, usage: acc.usage, endedAtMillis });
  });

  const applyImplementSuccess = Effect.fn("Executor.applyImplementSuccess")(function* (
    workspace: RegisteredWorkspace,
    item: EligibleWork,
    runId: RunId,
    acc: RunAccumulator,
  ) {
    const session = yield* sessionOf(acc.session);
    const endedAtMillis = yield* Clock.currentTimeMillis;
    yield* workSource.setRoles(workspace, item.id, { remove: ["ready-for-agent"], add: [] });
    yield* workSource.recordAttempt(workspace, item.id, {
      stage: "implement",
      outcome: "succeeded",
      atMillis: endedAtMillis,
    });
    yield* ledger.updateRun(runId, { status: "succeeded", session, usage: acc.usage, endedAtMillis });
  });

  const completeImplement = Effect.fn("Executor.completeImplement")(function* (
    workspace: RegisteredWorkspace,
    item: EligibleWork,
    runId: RunId,
    acc: RunAccumulator,
  ) {
    const result = parseImplementResult(acc.text);
    if (result === "opened-pr") {
      return yield* applyImplementSuccess(workspace, item, runId, acc);
    }
    const session = yield* sessionOf(acc.session);
    const reason = agentFailureReason(acc.text, result === "stuck" ? "stuck" : "missing-sentinel");
    return yield* applyFailure(
      workspace,
      item,
      "ready-for-agent",
      runId,
      result !== "stuck",
      reason,
      session,
    );
  });

  const releaseClaim = Effect.fn("Executor.releaseClaim")(function* (
    workspace: RegisteredWorkspace,
    item: EligibleWork,
  ) {
    const result = yield* Effect.result(workSource.release(workspace, item.id));
    if (Result.isFailure(result)) {
      yield* Effect.logWarning("claim release failed", {
        stage: item.stage,
        item: item.id,
        error: result.failure,
      });
    }
  });

  const prepareImplement = Effect.fn("Executor.prepareImplement")(function* (
    workspace: RegisteredWorkspace,
    item: EligibleWork,
    resolved: ResolvedStage,
    branch: string,
  ) {
    const worktree = yield* worktrees.ensure(workspace, item);
    const last = yield* ledger.latestRunByBranch(workspace.config.name, branch);
    return harnessRequest(
      resolved,
      worktree.path,
      buildImplementPrompt(resolved, item),
      last?.session ?? null,
    );
  });

  const triageOps = (workspace: RegisteredWorkspace, item: EligibleWork, resolved: ResolvedStage) =>
    ({
      resolved,
      branch: null,
      prepare: Effect.succeed(
        harnessRequest(resolved, workspace.config.checkoutPath, buildTriagePrompt(resolved, item), null),
      ),
      complete: (runId: RunId, acc: RunAccumulator) => applyTriageSuccess(workspace, item, runId, acc),
      handoffRole: handoffRoleFor("triage"),
    }) satisfies StageOps;

  const implementOps = (workspace: RegisteredWorkspace, item: EligibleWork, resolved: ResolvedStage) => {
    const branch = branchName(item);
    return {
      resolved,
      branch,
      prepare: prepareImplement(workspace, item, resolved, branch),
      complete: (runId: RunId, acc: RunAccumulator) => completeImplement(workspace, item, runId, acc),
      handoffRole: handoffRoleFor("implement"),
    } satisfies StageOps;
  };

  const followUpMarker = (context: FollowUpContext) => ({
    checks: context.checks,
    humanCommentAtMillis: context.humanCommentAtMillis,
    noProgress: context.noProgress,
  });

  const applyFollowUpSuccess = Effect.fn("Executor.applyFollowUpSuccess")(function* (
    workspace: RegisteredWorkspace,
    item: EligibleWork,
    runId: RunId,
    acc: RunAccumulator,
    context: FollowUpContext,
  ) {
    const session = yield* sessionOf(acc.session);
    const endedAtMillis = yield* Clock.currentTimeMillis;
    yield* workSource.recordFollowUp(workspace, item.id, followUpMarker(context));
    yield* workSource.recordAttempt(workspace, item.id, {
      stage: "follow-up",
      outcome: "succeeded",
      atMillis: endedAtMillis,
    });
    yield* ledger.updateRun(runId, { status: "succeeded", session, usage: acc.usage, endedAtMillis });
  });

  const completeFollowUp = Effect.fn("Executor.completeFollowUp")(function* (
    workspace: RegisteredWorkspace,
    item: EligibleWork,
    runId: RunId,
    acc: RunAccumulator,
    context: FollowUpContext,
  ) {
    const result = parseFollowUpResult(acc.text);
    if (result === "pushed") {
      return yield* applyFollowUpSuccess(workspace, item, runId, acc, context);
    }
    const session = yield* sessionOf(acc.session);
    const reason = agentFailureReason(acc.text, result === "stuck" ? "stuck" : "missing-sentinel");
    return yield* applyFailure(workspace, item, null, runId, result !== "stuck", reason, session);
  });

  const prepareFollowUp = Effect.fn("Executor.prepareFollowUp")(function* (
    workspace: RegisteredWorkspace,
    item: EligibleWork,
    resolved: ResolvedStage,
    branch: string,
    context: FollowUpContext,
  ) {
    const worktree = yield* worktrees.ensure(workspace, item);
    const last = yield* ledger.latestRunByBranch(workspace.config.name, branch);
    const now = yield* Clock.currentTimeMillis;
    const decision = decideResume({
      sessionId: last?.session ?? null,
      lastRunStartedAtMillis: last?.startedAtMillis ?? null,
      lastRunTotalTokens: last?.usage?.totalTokens ?? null,
      now,
      worktreeRecreated: worktree.created,
      fresh: context.fresh,
      maxAgeMillis: resolved.resumeMaxAgeMillis,
      maxTokens: resolved.resumeMaxTokens,
    });
    return harnessRequest(
      resolved,
      worktree.path,
      buildFollowUpPrompt(resolved, item),
      decision.kind === "resume" ? decision.sessionId : null,
    );
  });

  const followUpOps = (workspace: RegisteredWorkspace, item: EligibleWork, resolved: ResolvedStage) => {
    const branch = branchName(item);
    const context = item.followUp ?? defaultFollowUp;
    return {
      resolved,
      branch,
      prepare: prepareFollowUp(workspace, item, resolved, branch, context),
      complete: (runId: RunId, acc: RunAccumulator) => completeFollowUp(workspace, item, runId, acc, context),
      handoffRole: handoffRoleFor("follow-up"),
    } satisfies StageOps;
  };

  const handoffStalled = Effect.fn("Executor.handoffStalled")(function* (
    workspace: RegisteredWorkspace,
    item: EligibleWork,
  ) {
    const atMillis = yield* Clock.currentTimeMillis;
    const context = item.followUp ?? defaultFollowUp;
    yield* workSource.recordFollowUp(
      workspace,
      item.id,
      followUpMarker(context),
      `Follow-up made no progress after ${context.noProgress} attempts — neither the checks turned green nor a human responded. Handing this to a human.`,
    );
    yield* workSource.setRoles(workspace, item.id, { remove: [], add: ["ready-for-human"] });
    yield* workSource.recordAttempt(workspace, item.id, {
      stage: "follow-up",
      outcome: "abandoned",
      atMillis,
    });
  });

  const opsFor = (workspace: RegisteredWorkspace, item: EligibleWork, resolved: ResolvedStage) => {
    if (item.stage === "implement") return implementOps(workspace, item, resolved);
    if (item.stage === "follow-up") return followUpOps(workspace, item, resolved);
    return triageOps(workspace, item, resolved);
  };

  const runClaimed = Effect.fn("Executor.runClaimed")(function* (
    workspace: RegisteredWorkspace,
    item: EligibleWork,
    ops: StageOps,
    startedAtMillis: number,
  ) {
    const runId = yield* nextRunId(startedAtMillis);
    const record: RunRecord = {
      id: runId,
      workspace: workspace.config.name,
      workItem: item.id,
      stage: item.stage,
      harness: ops.resolved.harness,
      branch: ops.branch,
      session: null,
      usage: null,
      status: "running",
      startedAtMillis,
      endedAtMillis: null,
    };
    yield* ledger.insertRun(record);
    const outcome = yield* Effect.result(
      ops.prepare.pipe(
        Effect.flatMap(
          (request): Effect.Effect<RunAccumulator, PrepareError | HarnessError> => foldRun(record, request),
        ),
      ),
    );
    if (Result.isSuccess(outcome)) {
      return yield* ops.complete(runId, outcome.success);
    }
    return yield* applyFailure(
      workspace,
      item,
      ops.handoffRole,
      runId,
      retryableOf(outcome.failure),
      prepareFailureReason(outcome.failure),
      null,
    );
  });

  const runOrHandoff = Effect.fn("Executor.runOrHandoff")(function* (
    workspace: RegisteredWorkspace,
    item: EligibleWork,
    resolved: ResolvedStage,
    startedAtMillis: number,
  ) {
    if (item.stage === "follow-up" && item.followUp?.stalled) {
      return yield* handoffStalled(workspace, item);
    }
    yield* runClaimed(workspace, item, opsFor(workspace, item, resolved), startedAtMillis);
  });

  const execute = Effect.fn("Executor.execute")(function* (
    workspace: RegisteredWorkspace,
    item: EligibleWork,
  ) {
    const resolved = resolveStage(workspace.config, item.stage);
    if (!resolved?.enabled) {
      return false;
    }
    const startedAtMillis = yield* Clock.currentTimeMillis;
    const claimed = yield* tryClaim(workspace, item, startedAtMillis);
    if (!claimed) {
      return false;
    }
    yield* runOrHandoff(workspace, item, resolved, startedAtMillis).pipe(
      Effect.ensuring(releaseClaim(workspace, item)),
    );
    return true;
  });

  return { execute } as const;
});

export class Executor extends Context.Service<Executor, Effect.Success<typeof make>>()(
  "@clanker-forge/engine/Executor",
) {}

export const layer = Layer.effect(Executor, make);
