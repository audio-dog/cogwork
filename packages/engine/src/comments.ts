import type { LifecycleStage } from "@clanker-forge/contracts";

const attribution = "> *This was posted by clanker-forge.*";

const resultLine = /^\s*(?:IMPLEMENT|FOLLOWUP|TRIAGE)-(?:RESULT|DECISION):.*$/gim;
const htmlMarker = /<!--\s*clanker-forge:[^>]*-->/g;
const textMarker = /^[ \t]*clanker-forge:.*$/gm;

const stripMarkers = (text: string) => text.replace(htmlMarker, "").replace(textMarker, "");

const maxReasonChars = 800;

export type HandoffCause =
  | { readonly kind: "max-attempts"; readonly attempts: number }
  | { readonly kind: "non-retryable" }
  | { readonly kind: "crash-loop"; readonly crashes: number };

const attemptWord = (count: number) => (count === 1 ? "attempt" : "attempts");

export const oneLine = (text: string) => text.replace(/\s+/g, " ").trim();

export const truncate = (text: string, max = maxReasonChars) => {
  const trimmed = text.trim();
  if (trimmed.length <= max) return trimmed;
  return `${trimmed.slice(0, Math.max(0, max - 1)).trimEnd()}…`;
};

export const stripResultLines = (text: string) => text.replace(resultLine, "").trim();

export const triageProposalAttribution = "> *This was generated by AI during triage.*";

export const triageProposalBody = (text: string) =>
  `${triageProposalAttribution}\n\n${stripResultLines(text)}`;

export const parseTriageProposal = (body: string) => {
  if (!body.startsWith(triageProposalAttribution)) return null;
  const text = body.slice(triageProposalAttribution.length).trim();
  return text.length === 0 ? null : text;
};

export const shellQuote = (value: string) => `'${value.replaceAll("'", "'\\''")}'`;

export const attachCommand = (checkoutPath: string, sessionId: string) =>
  `cd ${shellQuote(checkoutPath)} && agent --resume ${shellQuote(sessionId)}`;

export const recoveryReason = "worker did not survive a daemon restart";

export const statusReason = (reason: string) => oneLine(truncate(stripMarkers(reason)));

export const prepareFailureReason = (error: {
  readonly _tag: string;
  readonly message: string;
  readonly command?: string;
  readonly operation?: string;
}) => {
  if (error._tag === "GitError" && error.command) return `git ${error.command}: ${error.message}`;
  if (error._tag === "WorktreeFsError" && error.operation) {
    return `${error.operation}: ${error.message}`;
  }
  return error.message;
};

export const agentFailureReason = (text: string, kind: "stuck" | "missing-sentinel") => {
  const cleaned = truncate(stripResultLines(text));
  if (kind === "stuck") return cleaned || "agent reported stuck";
  return cleaned ? `agent produced no result line — ${cleaned}` : "agent produced no result line";
};

const crashWord = (count: number) => (count === 1 ? "crash" : "crashes");

const headline = (stage: LifecycleStage, cause: HandoffCause) => {
  if (cause.kind === "max-attempts") {
    return `**Exhausted after ${cause.attempts} failed ${stage} ${attemptWord(cause.attempts)}.**`;
  }
  if (cause.kind === "crash-loop") {
    return `**Exhausted after ${cause.crashes} consecutive ${stage} ${crashWord(cause.crashes)}.**`;
  }
  return `**Exhausted: ${stage} hit a non-retryable failure.**`;
};

export const handoffComment = (
  stage: LifecycleStage,
  cause: HandoffCause,
  reason: string,
  resume: string | undefined,
) => {
  const lines = [
    attribution,
    "",
    headline(stage, cause),
    "",
    "Applied `ready-for-human`; a human needs to take over.",
    "",
    `Last failure: ${truncate(stripMarkers(reason))}`,
  ];
  return resume === undefined
    ? lines.join("\n")
    : [...lines, "", "Resume the session manually:", "", "```sh", resume, "```"].join("\n");
};
